def bitmap(ch):
    """list of 7 rows, each a string of 5 '0'/'1' characters"""
    return ROWS.get(ch.upper(), ROWS['?']).split()


def build_ttf(path):
    unit = 120                       # one font pixel; em = 8 rows
    chars = [c for c in ROWS]
    names = ['.notdef'] + ['g%d' % ord(c) for c in chars]
    glyphs = {}
    pen = TTGlyphPen(None)
    glyphs['.notdef'] = pen.glyph()
    for c in chars:
        pen = TTGlyphPen(None)
        for ry, row in enumerate(bitmap(c)):
            for rx, bit in enumerate(row):
                if bit == '1':
                    x0, y0 = rx * unit, (7 - ry) * unit + unit          # baseline sits one pixel above the bottom of the em
                    pen.moveTo((x0, y0)); pen.lineTo((x0, y0 + unit)); pen.lineTo((x0 + unit, y0 + unit)); pen.lineTo((x0 + unit, y0)); pen.closePath()
        glyphs['g%d' % ord(c)] = pen.glyph()
    cmap = {ord(c): 'g%d' % ord(c) for c in chars}
    cmap.update({ord(c.lower()): 'g%d' % ord(c) for c in chars if c.isalpha()})     # lower case shows as capitals
    fb = FontBuilder(960, isTTF=True)
    fb.setupGlyphOrder(names)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics({n: (720, 0) for n in names})
    fb.setupHorizontalHeader(ascent=900, descent=-60)
    fb.setupNameTable({'familyName': 'AshPixel', 'styleName': 'Regular'})
    fb.setupOS2(sTypoAscender=900, sTypoDescender=-60, usWinAscent=900, usWinDescent=60)
    fb.setupPost()
    fb.save(path)
